"""Refresh the bundled RSS snapshot: python3 scripts/update_podcast.py [feed.xml]."""
import json
from pathlib import Path
import sys
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
FEED = 'https://feed.firstory.me/rss/user/cmq5jhwm702rk01zl3m029l0a'
ITUNES = '{http://www.itunes.com/dtds/podcast-1.0.dtd}'

def main():
    if len(sys.argv) > 1:
        raw = Path(sys.argv[1]).read_bytes()
    else:
        with urllib.request.urlopen(FEED, timeout=30) as response:
            raw = response.read()
    channel = ET.fromstring(raw).find('channel')
    if channel is None:
        raise ValueError('RSS channel missing; snapshot unchanged')
    episodes = []
    for item in channel.findall('item'):
        enclosure = item.find('enclosure')
        episodes.append({
            'title': item.findtext('title', '').strip(),
            'description': item.findtext('description', ''),
            'date': item.findtext('pubDate', ''),
            'link': item.findtext('link', ''),
            'season': item.findtext(ITUNES + 'season', ''),
            'duration': item.findtext(ITUNES + 'duration', ''),
            'audio': enclosure.get('url', '') if enclosure is not None else '',
        })
    if not episodes:
        raise ValueError('Empty feed; snapshot unchanged')
    payload = json.dumps(episodes, ensure_ascii=False).replace('<', '\\u003c')
    (ROOT / 'js/podcast-data.js').write_text('// Generated by scripts/update_podcast.py\nwindow.podcastEpisodes = ' + payload + ';\n')
    print(f'Saved {len(episodes)} episodes')

if __name__ == '__main__':
    main()
